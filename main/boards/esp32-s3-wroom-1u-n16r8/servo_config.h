#pragma once

/* ========== 舵机模块配置（行为参数）==========
 * ⚠️ **引脚不在这里** —— 由板级 `config.h` 的 B 区提供（`SERVO_X_GPIO` / `SERVO_Y_GPIO`）。
 *    这是本目录的惯例（见 radar_config.h 的文件头说明）：硬件绑定的东西
 *    （引脚 / UART 号 / 波特率）放板级 config.h，与硬件无关的行为参数放各自的
 *    `*_config.h`。
 *
 * 本模块只驱动 **X 轴**（水平，持续跟踪说话人）。Y 轴（俯仰）本板**没装**，
 * 接口保留但由 SERVO_Y_ENABLE 关掉（默认 0）。
 *
 * 【行为总览】进入对话（Listening / Speaking）→ 持续读雷达跟踪人；
 *            退出对话（Idle 等）→ 平滑回中。
 *            详见 servo.cc 的「控制模型」说明。
 */

/* 总开关：置 0 则完全不启动舵机（不配 LEDC、不建任务、不输出日志）。
 * 代码始终参与编译，此开关只控制运行期行为 —— 出问题时改这一个宏即可整体回退。 */
#ifndef SERVO_LOOK_ENABLE
#define SERVO_LOOK_ENABLE 1
#endif

/* ── 运动参数 ────────────────────────────────────────────────────────── */

/* 「转满 180° 需要多久」（ms）—— 本模块用它换算**限速**：每拍（20ms）最多转
 * 180 × 20 / SERVO_LOOK_MS 度（**整数除法，所以取值是离散的**，见下表）。
 *
 * 它决定**最快能转多快**，全部移动共用这一个上限：
 *   ① 唤醒后第一次锁定你 / 退出对话回中   —— 目标角突变的整段行程
 *   ② 对话中的持续跟随                   —— 目标角连续小量变化
 * （② 通常碰不到这个上限：人慢慢走动时目标角本来就慢慢移。）
 *
 * | SERVO_LOOK_MS | 每拍 | 角速度 | 转 90° 要 |
 * |---|---|---|---|
 * | 400    | 9° | 450°/s | 0.20s |
 * | 600    | 6° | 300°/s | 0.30s |
 * | 800    | 4° | 200°/s | 0.45s |
 * | **1200** | **3°** | **150°/s** | **0.60s** | ← **现默认**
 * | 1600   | 2° | 100°/s | 0.90s |
 * | 2000   | 1° | 50°/s  | 1.80s | ← 再往大调就"几乎不动了"（量化到底）
 *
 * ⚠️ **别调太慢**：跟踪时人走动会产生角速度（1m/s 从 2m 外走过约 29°/s），
 *    低于那个值头就会跟不上人。150°/s 有约 5 倍余量。
 *
 * 实测依据（舵机数据手册）：空载速度 ≤0.09s/60° = **667°/s**，本表全部远低于它，
 * 不会出现"舵机追不上"的顿挫（若想更快也别超过 ~500°/s，带负载会缩水）。 */
#ifndef SERVO_LOOK_MS
#define SERVO_LOOK_MS 1200
#endif

/* 方位角 → 舵机角 的增益，**同时是方向标定旋钮，而且是唯一的那个**。
 *
 * ⚠️ 为什么只有一个旋钮：本模块的角度直接取自 `radar_snapshot()` 的 x_mm，
 *    而那个字段已经按 `DESKBOT_RADAR_X_SIGN` 规范化过（契约：**负 = 机器人左侧**）。
 *    所以「LLM 口头说的方位」和「头实际转的方向」**同源**，不可能互相打架。
 *    剩下的唯一不确定性是【舵机装反了】，由本宏标定：
 *      站到机器人左侧说话 → 头转向你 ✅ ；头转向反了 → 改成 `-1.0f`。
 *
 *    ⚠️ 原项目这里有 **两个独立**的符号旋钮（`DESKBOT_LOOK_GAIN` 作用于 LD2450 原始
 *       x_mm、`DESKBOT_RADAR_X_SIGN` 作用于规范化后的 x_mm），改一个不改另一个就会出现
 *       「LLM 说人在左边、头却往右转」。本移植刻意只留一个 —— 别再引入第二个。 */
#ifndef SERVO_LOOK_GAIN
#define SERVO_LOOK_GAIN 1.0f
#endif

/* ── 跟踪滤波 ────────────────────────────────────────────────────────── */

/* 目标角的一阶低通系数（0~1，每拍作用一次）。
 *
 * 为什么必须滤波：LD2450 的坐标抖动有几十 mm，1m 处换成角度就是好几度。
 * 不滤的话目标角会一直跳，头跟着抖抖索索。
 *
 * 时间常数 ≈ 20ms / (1-α)：
 *   0.10 → 约 200ms（很稳，跟随略钝）
 *   0.25 → 约 70ms （默认，跟手又不抖）
 *   0.50 → 约 20ms （跟得很紧，但雷达的抖动会透传过来）
 *
 * 嫌跟得慢/发飘就调这个，别去动 SERVO_LOOK_MS（那个是限速）。 */
#ifndef SERVO_TRACK_SMOOTH
#define SERVO_TRACK_SMOOTH 0.25f
#endif

/* 死区（度）：目标与当前位置相差小于这个值就**不动**。
 *
 * 作用：人站着不动时，滤波后的目标会在真实角度附近微微漂，
 * 没有死区舵机就会一直做极小的修正（听得见的嗡嗡声 + 机械磨损）。
 * 有了它，人静止时头会**完全停住**。
 *
 * ⚠️ 注意这**不违反**「绝不加角度阈值」那条教训 —— 那条针对的是**触发去重**
 *    （当时加阈值会把整次转向吞掉）。这里的死区作用在**跟踪的运动量**上，
 *    最多让头停在离目标 2° 的地方，下一个人一动就继续跟。
 *    默认 2° ≈ 舵机 13µs 的脉宽差，肉眼看不出来。 */
#ifndef SERVO_TRACK_DEADBAND_DEG
#define SERVO_TRACK_DEADBAND_DEG 2
#endif

/* 跟踪期间的周期日志间隔（ms）；**置 0 关闭**。
 * 调试滤波/死区时很有用（能看到"目标角 vs 实际角"）；调完建议置 0，
 * 否则一次长对话会刷出不少行。 */
#ifndef SERVO_TRACK_LOG_MS
#define SERVO_TRACK_LOG_MS 2000
#endif

/* ── 限位与标定 ──────────────────────────────────────────────────────── */

/* 开机归中角（度）：上电写一次，给出一个确定的初始朝向
 * （原项目 `setup_head()` 也这么做）。也是**退出对话后的回中位置**。 */
#ifndef SERVO_CENTER_DEG
#define SERVO_CENTER_DEG 90
#endif

/* X 轴软件限位（度）。
 *
 * ⚠️ 这只是**电气**限位；机械硬限位通常比 0~180 窄得多。
 *    上机实测后应收窄（例如 15 / 165）—— 命令角超出机械行程会让舵机**堵转**，
 *    堵转电流 200~400mA，供电没做好的话会把整机电源拉跌（ESP32 复位 / 屏幕花屏）。 */
#ifndef SERVO_X_MIN_DEG
#define SERVO_X_MIN_DEG 0
#endif
#ifndef SERVO_X_MAX_DEG
#define SERVO_X_MAX_DEG 180
#endif

/* 舵机脉宽标定（µs）：**软件 0° 和 180° 分别发多宽的脉冲**。
 *
 * ⚠️⚠️ 这是整个舵机模块最容易搞错、也最该实测的一项。
 *    它**不是**「舵机的规格」，而是**你这颗舵机的规格**：
 *      · 常见 hobby 舵机（含小智 otto-robot）是 **500~2500µs 走 180°**；
 *      · 也有一批小舵机是 **1000~2000µs 走 180°**。
 *    填错的表现：软件显示转 180°，肉眼只看到 60°~90° ——
 *    量级对不上就是这里错了，不是驱动代码错。
 *
 * ── 怎么标定 ─────────────────────────────────────────────
 *   1. 开着 SERVO_SELF_TEST_ON_BOOT（上电会走一趟两端），盯着**舵盘/输出轴本身**
 *      看（有连杆先脱开），别看头部 —— 要先排除「连杆减速」这个机械因素。
 *   2. 若舵盘没有走满半圈 → 加宽本范围（先试 500 / 2500）。
 *   3. 若舵机在某一端**嗡嗡响/卡住**，说明顶到机械硬限位了 → 把那一端往回收
 *      100µs 再试（例如 600 / 2400）。收敛到"刚好走满且两端都不响"。
 *
 * ✅ 好消息：**归中位置不受本范围影响**。90° 在任何对称范围下都算作
 *    1500µs（中立位），所以调这两个值不会让机器人「正前方」变歪。
 *
 * ✅✅ **已实机确认（2026-10-12）**：本板这颗 3.7g 舵机就是 **500~2500µs 走 180°**，
 *    与数据手册的「信号宽度范围 500-2500µs」一致（手册另列「操作角度 90°/180°」
 *    两个型号，本板是 **180°** 那款）。
 *    原先填的 1000~2000µs（照抄 brufik 原项目的值）只走了约 60° ——
 *    那是**原项目里就存在的标定错误**，不是这次移植引入的。
 *    ⚠️ 所以：**别再照抄 brufik 的 1000/2000**。
 *
 * ⚡ 供电（数据手册：**工作电压 3.7~5V**）：
 *    注意 **ESP32 的 3.3V 轨低于本舵机的规格下限** —— 用 3.3V 喂它属于超规格运行，
 *    表现为无力/抖/堵转不转。**舵机 VCC 接 5V(VBAT)、与 ESP32 共地**，
 *    就近并 100~470µF 电解；否则舵机动作时会把母线拉跌，
 *    连累同一路供电的雷达（实测见过 LD2450 被拉得断流 5 秒）。 */
#ifndef SERVO_PULSE_MIN_US
#define SERVO_PULSE_MIN_US 500
#endif
#ifndef SERVO_PULSE_MAX_US
#define SERVO_PULSE_MAX_US 2500
#endif

/* ── 开机自检 ──────────────────────────────────────────────
 * 上电后（完成归中）把 X 轴走一趟：MAX → MIN → 归中，每站停 SERVO_SELF_TEST_HOLD_MS。
 *
 * 用途：**一眼看出舵机的实际行程和方向**（软件限位是电气的，物理到不到得了要
 * 用眼睛确认）。两端就是 SERVO_X_MIN/MAX_DEG —— 所以你把限位收窄之后，
 * 自检走的也正好是程序实际会用的那段行程。
 *
 * ⚠️ 三个注意点：
 *   1. 全程约 11 秒，这期间不跟踪（自检完自动接上）。
 *   2. 如果舵机在两端「嗡嗡」响或卡住不动，说明**撞到机械硬限位了，正在堵转**
 *      （200~400mA，供电不好会把整机拉跌）→ 立刻把本开关置 0，并收窄
 *      SERVO_X_MIN/MAX_DEG。
 *   3. 调试完建议置 0：否则每次上电都要甩十来秒。
 */
#ifndef SERVO_SELF_TEST_ON_BOOT
#define SERVO_SELF_TEST_ON_BOOT 1
#endif

/* 自检每一站的停留时长（ms）。转向过程本身用 SERVO_LOOK_MS 限速。 */
#ifndef SERVO_SELF_TEST_HOLD_MS
#define SERVO_SELF_TEST_HOLD_MS 5000
#endif

/* ── Y 轴（俯仰）──────────────────────────────────────────────
 * 本板**没装** Y 舵机 → 默认 0：不配 LEDC 通道、不写角度。
 * 接口 `servo_set_y_deg()` 保留，装了以后置 1 即可。
 * ⚠️ 该路径**未上机验证**（本板没有硬件可测）。 */
#ifndef SERVO_Y_ENABLE
#define SERVO_Y_ENABLE 0
#endif
#ifndef SERVO_Y_MIN_DEG
#define SERVO_Y_MIN_DEG 70 /* 原项目 Y 是 9g 大舵机，俯仰行程只有 70~110° */
#endif
#ifndef SERVO_Y_MAX_DEG
#define SERVO_Y_MAX_DEG 110
#endif
#ifndef SERVO_Y_CENTER_DEG
#define SERVO_Y_CENTER_DEG 90
#endif
